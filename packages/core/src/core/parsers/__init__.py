"""Dispatches a file path to the right format parser based on its extension."""
# Todo: Review this code. Is this the right way to do it inside the __init__ module?

from __future__ import annotations

from pathlib import Path

from core.models.document import Document
from core.parsers import docx_parser, eml_parser, markdown_parser, msg_parser, pdf_parser, txt_parser

# Todo: Add support for folder parsing with a collection of documents that sorts the whole folder as a unit.

_PARSERS = {
    ".pdf": pdf_parser.parse,
    ".docx": docx_parser.parse,
    ".txt": txt_parser.parse,
    ".md": markdown_parser.parse,
    ".markdown": markdown_parser.parse,
    ".msg": msg_parser.parse,
    ".eml": eml_parser.parse,
}

SUPPORTED_EXTENSIONS = frozenset(_PARSERS)


def parse_document(path: Path) -> Document:
    """
    Parses a document based on the file extension and returns a processed Document object.

    Parse ``path`` with the parser registered for its extension.

    This function uses the file's extension to find an appropriate parser from a
    predefined set of parsers and invokes it. If no parser is found for the given
    extension, an exception is raised.

    Args:
        path (Path): The path to the document file to be parsed. The file extension
            is used to determine the appropriate parser.

    Raises:
        ValueError: If no parser is registered for the file's extension.

    Returns:
        Document: A processed Document object generated by the corresponding parser.
    Todo:
        - Link ValueError to logging.
        - Check that ValueError doesn't stop code.
        - Is there an existing well established library for parsing documents?
    """

    parser = _PARSERS.get(path.suffix.lower())
    if parser is None:
        raise ValueError(f"No parser registered for extension '{path.suffix}' ({path})")  # noqa: TRY003
    return parser(path)
